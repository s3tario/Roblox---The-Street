#!/usr/bin/env python3
"""Upload the generated Shirt/Pants templates to Roblox and record their ids in Config/ClothingIds.luau.

Uses the Roblox Open Cloud Assets API (https://apis.roblox.com/assets/v1). Each PNG in assets/clothing is
uploaded as a Decal; the script waits for the upload operation to finish, looks up the image id inside the
decal (that is the id a Shirt/Pants template needs), and writes every id into
src/shared/Config/ClothingIds.luau. Only the Python 3 standard library is needed.

    export ROBLOX_API_KEY=...            # Open Cloud key with "asset:read" and "asset:write"
                                         # (plus "legacy-asset:manage" for the image-id lookup)
    export ROBLOX_CREATOR_ID=12345678    # your user id (or a group id with --group)
    python3 tools/clothing/upload.py               # upload new or changed templates
    python3 tools/clothing/upload.py --only suit_navy_2b oxford_white
    python3 tools/clothing/upload.py --dry-run     # show what would be uploaded
    python3 tools/clothing/upload.py --init        # (re)write ClothingIds.luau with every id set to 0

Progress is kept in assets/clothing/uploads.json (file hash, decal id, image id), so a re-run only uploads
templates whose PNG changed. Run it from the repository root.
"""

import argparse
import hashlib
import json
import os
import re
import struct
import subprocess
import sys
import time
import urllib.error
import urllib.request
import uuid

ROOT = os.path.abspath(os.path.join(os.path.dirname(__file__), "..", ".."))
ASSETS_DIR = os.path.join(ROOT, "assets", "clothing")
STATE_FILE = os.path.join(ASSETS_DIR, "uploads.json")
OUT_FILE = os.path.join(ROOT, "src", "shared", "Config", "ClothingIds.luau")

API = "https://apis.roblox.com/assets/v1"
DELIVERY = "https://apis.roblox.com/asset-delivery-api/v1/assetId/{id}"
PUBLIC_DELIVERY = "https://assetdelivery.roblox.com/v1/asset/?id={id}"


# ---------------------------------------------------------------------------------------------------------
# Catalog
# ---------------------------------------------------------------------------------------------------------
def load_catalog(path=None):
    """Catalog entries from tools/clothing/export.luau (runs Lune unless a JSON path is given)."""
    if path:
        with open(path, "r", encoding="utf-8") as f:
            return json.load(f)["items"]
    try:
        out = subprocess.run(
            ["lune", "run", "tools/clothing/export"],
            cwd=ROOT,
            check=True,
            capture_output=True,
            text=True,
        ).stdout
    except (OSError, subprocess.CalledProcessError) as e:
        sys.exit("Couldn't run 'lune run tools/clothing/export' (is Lune installed?): %s" % e)
    start = out.find("{")
    return json.loads(out[start:])["items"]


def template_items(items):
    """(item, kind) pairs for every visible top/outer ("shirt") and bottom ("pants") item."""
    out = []
    for it in items:
        if it.get("hidden") or not it.get("template"):
            continue
        out.append((it, it["template"]))
    return out


# ---------------------------------------------------------------------------------------------------------
# ClothingIds.luau
# ---------------------------------------------------------------------------------------------------------
HEADER = """--!strict
-- Optional uploaded 2D clothing templates (owned by `wardrobe`). GENERATED by tools/clothing/upload.py; edit by
-- re-running it (or by hand: paste an image id in place of a 0).
--   shirts[itemId] = image asset id of <itemId>_shirt.png (top and outer items)
--   pants[itemId]  = image asset id of <itemId>_pants.png (bottom items)
-- 0 = not uploaded. WardrobeService puts a Shirt/Pants with these templates under the 3D Career Look layers when
-- an id is set; the game looks complete without any of them.

export type Ids = { shirts: { [string]: number }, pants: { [string]: number } }

local ids: Ids = {
"""


def write_luau(items, ids):
    """ids = {"shirt": {itemId: n}, "pants": {itemId: n}}"""
    lines = [HEADER]
    for kind, key in (("shirt", "shirts"), ("pants", "pants")):
        lines.append("\t%s = {\n" % key)
        for it, k in template_items(items):
            if k != kind:
                continue
            n = int(ids.get(kind, {}).get(it["id"], 0) or 0)
            lines.append("\t\t%s = %d,\n" % (it["id"], n))
        lines.append("\t},\n")
    lines.append("}\n\nreturn ids\n")
    with open(OUT_FILE, "w", encoding="utf-8") as f:
        f.write("".join(lines))


def read_luau():
    """Existing ids from ClothingIds.luau (so hand-pasted ids survive a re-run)."""
    ids = {"shirt": {}, "pants": {}}
    if not os.path.exists(OUT_FILE):
        return ids
    kind = None
    with open(OUT_FILE, "r", encoding="utf-8") as f:
        for line in f:
            s = line.strip()
            if s.startswith("shirts = {"):
                kind = "shirt"
            elif s.startswith("pants = {"):
                kind = "pants"
            elif s.startswith("}"):
                kind = None
            elif kind:
                m = re.match(r"^([A-Za-z0-9_]+)\s*=\s*(\d+),?$", s)
                if m:
                    ids[kind][m.group(1)] = int(m.group(2))
    return ids


# ---------------------------------------------------------------------------------------------------------
# HTTP
# ---------------------------------------------------------------------------------------------------------
def http(method, url, api_key=None, body=None, headers=None, retries=4):
    hdrs = dict(headers or {})
    if api_key:
        hdrs["x-api-key"] = api_key
    delay = 2.0
    for attempt in range(retries + 1):
        req = urllib.request.Request(url, data=body, method=method, headers=hdrs)
        try:
            with urllib.request.urlopen(req, timeout=60) as resp:
                return resp.status, resp.read(), dict(resp.headers)
        except urllib.error.HTTPError as e:
            data = e.read()
            if e.code in (429, 500, 502, 503, 504) and attempt < retries:
                wait = float(e.headers.get("Retry-After") or delay)
                print("  HTTP %d, retrying in %.0fs" % (e.code, wait))
                time.sleep(wait)
                delay *= 2
                continue
            return e.code, data, dict(e.headers)
        except urllib.error.URLError as e:
            if attempt < retries:
                print("  network error (%s), retrying in %.0fs" % (e.reason, delay))
                time.sleep(delay)
                delay *= 2
                continue
            raise
    raise RuntimeError("unreachable")


def multipart(fields, files):
    """fields: {name: str}; files: {name: (filename, bytes, content_type)} -> (body, content_type)."""
    boundary = "----thestreet" + uuid.uuid4().hex
    parts = []
    for name, value in fields.items():
        parts.append(
            ("--%s\r\nContent-Disposition: form-data; name=\"%s\"\r\n\r\n%s\r\n" % (boundary, name, value)).encode()
        )
    for name, (filename, data, ctype) in files.items():
        head = "--%s\r\nContent-Disposition: form-data; name=\"%s\"; filename=\"%s\"\r\nContent-Type: %s\r\n\r\n" % (
            boundary,
            name,
            filename,
            ctype,
        )
        parts.append(head.encode() + data + b"\r\n")
    parts.append(("--%s--\r\n" % boundary).encode())
    return b"".join(parts), "multipart/form-data; boundary=%s" % boundary


def upload_decal(api_key, creator, path, display_name, description, asset_type):
    with open(path, "rb") as f:
        data = f.read()
    request = {
        "assetType": asset_type,
        "displayName": display_name[:50],
        "description": description[:1000],
        "creationContext": {"creator": creator},
    }
    body, ctype = multipart(
        {"request": json.dumps(request)},
        {"fileContent": (os.path.basename(path), data, "image/png")},
    )
    status, resp, _ = http("POST", API + "/assets", api_key, body, {"Content-Type": ctype})
    if status >= 300:
        raise RuntimeError("upload failed (HTTP %d): %s" % (status, resp.decode("utf-8", "replace")[:400]))
    op = json.loads(resp)
    return poll_operation(api_key, op)


def poll_operation(api_key, op, timeout=180):
    """Waits for an Assets API operation and returns the new asset id."""
    started = time.time()
    delay = 1.0
    while True:
        if op.get("done"):
            if "error" in op:
                raise RuntimeError("operation failed: %s" % json.dumps(op["error"]))
            asset_id = (op.get("response") or {}).get("assetId")
            if not asset_id:
                raise RuntimeError("operation finished without an asset id: %s" % json.dumps(op))
            return int(asset_id)
        if time.time() - started > timeout:
            raise RuntimeError("timed out waiting for %s" % (op.get("path") or op.get("operationId")))
        time.sleep(delay)
        delay = min(delay * 1.6, 8)
        path = op.get("path") or ("operations/%s" % op.get("operationId"))
        status, resp, _ = http("GET", "%s/%s" % (API, path), api_key)
        if status >= 300:
            raise RuntimeError("polling failed (HTTP %d): %s" % (status, resp[:300]))
        op = json.loads(resp)


# ---------------------------------------------------------------------------------------------------------
# Decal -> image id (the decal asset is a tiny model whose Decal.Texture points at the image)
# ---------------------------------------------------------------------------------------------------------
ID_PATTERN = re.compile(rb"(?:rbxassetid://|asset/?\?id=|assetId=)(\d{3,})")


def lz4_block_decompress(src, size):
    """Minimal LZ4 block decoder (enough for Roblox binary model chunks)."""
    dst = bytearray()
    i = 0
    n = len(src)
    while i < n:
        token = src[i]
        i += 1
        lit = token >> 4
        if lit == 15:
            while True:
                b = src[i]
                i += 1
                lit += b
                if b != 255:
                    break
        dst += src[i : i + lit]
        i += lit
        if i >= n:
            break
        offset = src[i] | (src[i + 1] << 8)
        i += 2
        match = token & 15
        if match == 15:
            while True:
                b = src[i]
                i += 1
                match += b
                if b != 255:
                    break
        match += 4
        start = len(dst) - offset
        for k in range(match):
            dst.append(dst[start + k])
    return bytes(dst[:size])


def binary_chunks(data):
    """Decoded chunk payloads of a binary .rbxm (empty list if it isn't one)."""
    if not data.startswith(b"<roblox!"):
        return []
    out = []
    pos = 32  # magic(8) + signature(6) + version(2) + classes(4) + instances(4) + reserved(8)
    while pos + 16 <= len(data):
        name = data[pos : pos + 4]
        clen, ulen, _ = struct.unpack("<III", data[pos + 4 : pos + 16])
        pos += 16
        if clen == 0:
            payload = data[pos : pos + ulen]
            pos += ulen
        else:
            raw = data[pos : pos + clen]
            pos += clen
            if raw[:4] == b"\x28\xb5\x2f\xfd":
                try:
                    import zstandard  # optional

                    payload = zstandard.ZstdDecompressor().decompress(raw, max_output_size=ulen)
                except Exception:
                    payload = b""
            else:
                try:
                    payload = lz4_block_decompress(raw, ulen)
                except Exception:
                    payload = b""
        out.append(payload)
        if name == b"END\x00":
            break
    return out


def image_id_from_model(data, decal_id):
    for blob in [data] + binary_chunks(data):
        for m in ID_PATTERN.finditer(blob):
            n = int(m.group(1))
            if n != decal_id:
                return n
    return None


def resolve_image_id(api_key, decal_id, attempts=6):
    """Looks up the image id inside a decal. New uploads can take a little while to become readable."""
    delay = 3.0
    for attempt in range(attempts):
        # Open Cloud asset delivery (needs the legacy-asset:manage scope) returns a short-lived download URL.
        status, resp, _ = http("GET", DELIVERY.format(id=decal_id), api_key)
        if status < 300:
            try:
                location = json.loads(resp).get("location")
            except ValueError:
                location = None
            if location:
                st2, model, _ = http("GET", location)
                if st2 < 300:
                    found = image_id_from_model(model, decal_id)
                    if found:
                        return found
        # Public asset delivery (works for assets you own while logged-out access is allowed).
        status, resp, _ = http("GET", PUBLIC_DELIVERY.format(id=decal_id), api_key)
        if status < 300:
            found = image_id_from_model(resp, decal_id)
            if found:
                return found
        if attempt < attempts - 1:
            time.sleep(delay)
            delay *= 1.5
    return None


# ---------------------------------------------------------------------------------------------------------
# Main
# ---------------------------------------------------------------------------------------------------------
def sha256(path):
    h = hashlib.sha256()
    with open(path, "rb") as f:
        h.update(f.read())
    return h.hexdigest()


def load_state():
    if os.path.exists(STATE_FILE):
        with open(STATE_FILE, "r", encoding="utf-8") as f:
            return json.load(f)
    return {}


def save_state(state):
    with open(STATE_FILE, "w", encoding="utf-8") as f:
        json.dump(state, f, indent=2, sort_keys=True)
        f.write("\n")


def main():
    ap = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    ap.add_argument("--api-key", default=os.environ.get("ROBLOX_API_KEY"), help="Open Cloud API key")
    ap.add_argument("--creator-id", default=os.environ.get("ROBLOX_CREATOR_ID"), help="user (or group) id")
    ap.add_argument("--group", action="store_true", help="the creator id is a group id")
    ap.add_argument("--only", nargs="*", help="item ids to upload (default: all)")
    ap.add_argument("--force", action="store_true", help="re-upload even if the PNG didn't change")
    ap.add_argument("--dry-run", action="store_true", help="list what would be uploaded and stop")
    ap.add_argument("--init", action="store_true", help="write ClothingIds.luau with every id set to 0")
    ap.add_argument("--catalog", help="catalog JSON from tools/clothing/export (default: run Lune)")
    ap.add_argument("--asset-type", default="Decal", help="Open Cloud asset type for the PNGs (default Decal)")
    args = ap.parse_args()

    items = load_catalog(args.catalog)

    if args.init:
        write_luau(items, {"shirt": {}, "pants": {}})
        print("wrote %s (all ids 0)" % os.path.relpath(OUT_FILE, ROOT))
        return

    ids = read_luau()
    state = load_state()
    todo = []
    for it, kind in template_items(items):
        if args.only and it["id"] not in args.only:
            continue
        path = os.path.join(ASSETS_DIR, "%s_%s.png" % (it["id"], kind))
        if not os.path.exists(path):
            print("skip %s: %s is missing (run generate.py first)" % (it["id"], os.path.basename(path)))
            continue
        key = "%s_%s" % (it["id"], kind)
        digest = sha256(path)
        prev = state.get(key) or {}
        have = ids.get(kind, {}).get(it["id"], 0)
        if not args.force and prev.get("sha256") == digest and prev.get("imageId") and have:
            continue
        todo.append((it, kind, path, key, digest))

    print("%d template(s) to upload" % len(todo))
    if args.dry_run or not todo:
        for it, kind, path, _, _ in todo:
            print("  %s (%s)" % (os.path.basename(path), it["name"]))
        if not todo:
            write_luau(items, ids)
        return

    if not args.api_key or not args.creator_id:
        sys.exit("Set ROBLOX_API_KEY and ROBLOX_CREATOR_ID (or pass --api-key and --creator-id).")
    creator = {"groupId": str(args.creator_id)} if args.group else {"userId": str(args.creator_id)}

    failures = 0
    for it, kind, path, key, digest in todo:
        label = "%s %s" % (it["name"], "Shirt" if kind == "shirt" else "Pants")
        print("uploading %s ..." % os.path.basename(path))
        try:
            decal_id = upload_decal(
                args.api_key,
                creator,
                path,
                label,
                "The Street clothing template for %s." % it["name"],
                args.asset_type,
            )
            image_id = resolve_image_id(args.api_key, decal_id)
            if not image_id:
                print(
                    "  uploaded as decal %d, but its image id isn't readable yet. Run again later, or open the"
                    " decal in Studio and paste its image id into ClothingIds.luau." % decal_id
                )
                state[key] = {"sha256": digest, "decalId": decal_id, "imageId": None}
                failures += 1
            else:
                print("  decal %d -> image %d" % (decal_id, image_id))
                state[key] = {"sha256": digest, "decalId": decal_id, "imageId": image_id}
                ids.setdefault(kind, {})[it["id"]] = image_id
        except Exception as e:  # keep going; one bad upload shouldn't lose the others
            print("  FAILED: %s" % e)
            failures += 1
        save_state(state)
        write_luau(items, ids)  # write as we go so an interrupted run keeps its progress

    print("done: %d uploaded, %d need attention" % (len(todo) - failures, failures))
    if failures:
        sys.exit(1)


if __name__ == "__main__":
    main()
